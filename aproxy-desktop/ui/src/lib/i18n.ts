const tables = (
  import.meta.env.DEV
    ? { 'zh-CN': { ...zh, ...zhProto }, en: { ...en, ...enProto } }
    : { 'zh-CN': zh, en }
) as Record<Lang, Record<Key, string>>;

export type MessageKey = Key;

/** 取文案。读 ui.lang（$state），所以在模板里调用会随语言切换自动刷新 */
export function t(key: Key, vars: Record<string, string | number> = {}): string {
  const template = tables[ui.lang][key];
  return template
    .replace(/\{(\w+):([^|}]*)\|([^}]*)\}/g, (_, name: string, one: string, other: string) =>
      Number(vars[name]) === 1 ? one : other,
    )
    .replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
}

export function fmtNum(n: number): string {
  return new Intl.NumberFormat(ui.lang).format(n);
}

/** 「N 分钟前」 */
export function ago(ms: number): string {
  const s = Math.max(0, Math.round(ms / 1000));
  if (s < 5) return t('time.justNow');
  if (s < 60) return t('time.secAgo', { n: s });
  const m = Math.floor(s / 60);
  if (m < 60) return t('time.minAgo', { n: m });
  const h = Math.floor(m / 60);
  if (h < 24) return t('time.hourAgo', { n: h });
  return t('time.dayAgo', { n: Math.floor(h / 24) });
}

/** 日志表格里的紧凑耗时：842ms、12.4s、5m 03s */
export function durShort(ms: number): string {
  if (ms < 1000) return t('dur.ms_short', { n: Math.round(ms) });
  if (ms < 60_000) return t('dur.s_short', { n: (ms / 1000).toFixed(ms < 10_000 ? 2 : 1) });
  const m = Math.floor(ms / 60_000);
  const s = Math.floor((ms % 60_000) / 1000);
  return t('dur.m_short', { m, s: String(s).padStart(2, '0') });
}

/** 正文里的耗时：842 毫秒、12.4 秒、1 分 12 秒 */
export function durLong(ms: number): string {
  if (ms < 1000) return t('dur.ms', { n: Math.round(ms) });
  if (ms < 60_000) return t('dur.s', { n: Number((ms / 1000).toFixed(1)) });
  const m = Math.floor(ms / 60_000);
  return t('dur.minSec', { m, s: Math.floor((ms % 60_000) / 1000) });
}

/** 运行时长：3 天 4 小时、5 小时 2 分、12 分钟 */
export function uptime(ms: number): string {
  const totalMin = Math.floor(ms / 60_000);
  const d = Math.floor(totalMin / 1440);
  const h = Math.floor((totalMin % 1440) / 60);
  const m = totalMin % 60;
  if (d > 0) return t('dur.dayHour', { d, h });
  if (h > 0) return t('dur.hourMin', { h, m });
  return t('dur.min', { m });
}

export function bytes(n: number): string {
  if (n < 1024) return `${n} B`;
  if (n < 1024 * 1024) return `${(n / 1024).toFixed(n < 10 * 1024 ? 1 : 0)} KB`;
  return `${(n / 1024 / 1024).toFixed(1)} MB`;
}

export function clock(ts: number): string {
  const d = new Date(ts);
  return [d.getHours(), d.getMinutes(), d.getSeconds()].map((v) => String(v).padStart(2, '0')).join(':');
}

export function stamp(ts: number): string {
  const d = new Date(ts);
  const date = [d.getFullYear(), d.getMonth() + 1, d.getDate()].map((v, i) => (i ? String(v).padStart(2, '0') : v)).join('-');
  return `${date} ${clock(ts)}.${String(d.getMilliseconds()).padStart(3, '0')}`;
}
